// Verifique uma temperatura.

// Menor que 15 -> Frio

// Entre 15 e 28 -> Agradável

// Maior que 28 -> Muito quente


let temp = 16

if( temp < 15){
    console.log(`Frio`);
}

else if(temp =15 && temp <=28){
    console.log(`agradavel`)
}

else {
    console.log(`muito quente`);
}